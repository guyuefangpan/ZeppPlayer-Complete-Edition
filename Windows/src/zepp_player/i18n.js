const dictionaries = { en, zh };

function detectDefault() {
    try {
        if (localStorage.getItem(LANG_KEY)) return localStorage.getItem(LANG_KEY);
    } catch (e) {}
    const nav = (typeof navigator !== "undefined" && navigator.language) || "";
    return nav.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export const I18n = {
    _locale: detectDefault(),

    get locale() {
        return this._locale;
    },

    setLanguage(locale) {
        this._locale = dictionaries[locale] ? locale : "zh";
        try { localStorage.setItem(LANG_KEY, this._locale); } catch (e) {}
    },

    t(key, fallback) {
        const dict = dictionaries[this._locale] || zh;
        if (dict[key] !== undefined) return dict[key];
        if (en[key] !== undefined) return en[key];
        return fallback !== undefined ? fallback : key;
    },

    // Apply data-i18n (text) and data-i18n-title (tooltip) attributes.
    apply(root = document) {
        root.querySelectorAll("[data-i18n]").forEach((el) => {
            el.textContent = this.t(el.getAttribute("data-i18n"), el.textContent);
        });
        root.querySelectorAll("[data-i18n-title]").forEach((el) => {
            el.setAttribute("title", this.t(el.getAttribute("data-i18n-title"), el.getAttribute("title") || el.getAttribute("data-i18n-title")));
        });
        const titleTag = root.querySelector("title");
        if (titleTag) titleTag.textContent = this.t("app.title", "ZeppPlayer");
    },
};

export default I18n;